#!/usr/bin/env python3
"""Interactive terminal setup: Uni-ID, folders and daily schedule.

Run via ./setup.sh (the installer starts it automatically). Every step can be
repeated later; existing values are shown as defaults.
"""

from __future__ import annotations

import argparse
import getpass
import os
import plistlib
import subprocess
import sys
from pathlib import Path

import settings

AGENT_PLIST = Path.home() / "Library" / "LaunchAgents" / f"{settings.LAUNCH_AGENT_LABEL}.plist"
SCHEDULED_COMMAND = settings.SUPPORT_DIR / "scheduled.command"


def ask(question: str, default: str = "") -> str:
    suffix = f" [{default}]" if default else ""
    answer = input(f"{question}{suffix}: ").strip()
    return answer or default


def yes(question: str, default: bool = True) -> bool:
    hint = "J/n" if default else "j/N"
    while True:
        answer = input(f"{question} ({hint}): ").strip().casefold()
        if not answer:
            return default
        if answer in ("j", "ja", "y", "yes"):
            return True
        if answer in ("n", "nein", "no"):
            return False


def setup_credentials() -> None:
    print("\n— Zugangsdaten —")
    print("Uni-ID und Passwort werden nur im macOS-Schlüsselbund gespeichert und ausschließlich")
    print("in das Anmeldeformular von idp.uni-mannheim.de eingetragen. Ohne gespeicherte Daten")
    print("öffnet sich bei jedem Lauf ein Browserfenster, in dem du dich selbst anmeldest.")
    current = settings.stored_username()
    if current:
        print(f"Aktuell gespeichert: {current}")
        if not yes("Andere Zugangsdaten speichern?", default=False):
            return
    elif not yes("Zugangsdaten jetzt speichern?"):
        return
    username = ask("Uni-ID (z. B. mmustermann)")
    if not username:
        print("Keine Uni-ID eingegeben – übersprungen.")
        return
    password = getpass.getpass("Passwort (wird nicht angezeigt): ")
    if not password:
        print("Kein Passwort eingegeben – übersprungen.")
        return
    settings.set_credentials(username, password)
    print(f"Gespeichert für {username}.")


def setup_folders() -> None:
    print("\n— Ordner —")
    data = settings.load()
    while True:
        semester = Path(ask("Wohin sollen die Kursmaterialien? (ein Unterordner pro Kurs)", data["semester_dir"])).expanduser()
        markdown = Path(ask("Wohin sollen die Markdown-Kopien für KI-Tools?", data["markdown_dir"])).expanduser()
        if markdown.resolve() == semester.resolve() or semester.resolve() in markdown.resolve().parents:
            print("Der Markdown-Ordner darf nicht im Materialordner liegen. Bitte einen anderen wählen.")
            continue
        break
    data["semester_dir"], data["markdown_dir"] = str(semester), str(markdown)
    data["markdown_after_sync"] = yes("Nach jedem Abgleich automatisch Markdown-Kopien für KI-Tools erzeugen?",
                                      default=True)
    data["headless"] = yes("Täglichen Abgleich ohne Browserfenster ausführen (nur mit gespeicherten Zugangsdaten)?",
                           default=bool(data["headless"]))
    settings.save(data)
    semester.mkdir(parents=True, exist_ok=True)
    if data["markdown_after_sync"]:
        markdown.mkdir(parents=True, exist_ok=True)
    print(f"Gespeichert in {settings.SETTINGS_FILE}")


def write_schedule(hour: int, minute: int) -> None:
    settings.SUPPORT_DIR.mkdir(parents=True, exist_ok=True)
    project = str(settings.PROJECT).replace("'", "'\\''")
    lock = str(settings.LOCK_FILE)
    log = str(settings.LOG_FILE).replace("'", "'\\''")
    home = str(Path.home()).replace("'", "'\\''")
    SCHEDULED_COMMAND.write_text(f"""#!/bin/zsh
# Generated by setup.py – started daily by the LaunchAgent {settings.LAUNCH_AGENT_LABEL}.
export HOME='{home}'
cd '{project}' || {{ print 'Projektordner nicht gefunden: {project}'; read -k 1; exit 1 }}
print -r -- "ILIAS-Abgleich gestartet: $(date '+%Y-%m-%d %H:%M:%S')"
/usr/bin/lockf -t 0 '{lock}' ./run.sh --use-settings 2>&1 | /usr/bin/tee -a '{log}'
run_exit=${{pipestatus[1]}}
print -r -- "ILIAS-Abgleich beendet mit Status $run_exit: $(date '+%Y-%m-%d %H:%M:%S')" | /usr/bin/tee -a '{log}'
if (( run_exit != 0 )); then
    print -r -- 'Bitte Fehlermeldung oben prüfen. Dieses Fenster bleibt bis zu einem Tastendruck geöffnet.'
    read -k 1 '?Taste drücken zum Schließen: '
fi
exit $run_exit
""", encoding="utf-8")
    SCHEDULED_COMMAND.chmod(0o755)
    AGENT_PLIST.parent.mkdir(parents=True, exist_ok=True)
    remove_schedule(quiet=True)
    with AGENT_PLIST.open("wb") as handle:
        plistlib.dump({
            "Label": settings.LAUNCH_AGENT_LABEL,
            # A visible Terminal window: macOS grants it access to ~/Documents, and you see progress.
            "ProgramArguments": ["/usr/bin/open", "-n", "-a", "Terminal", str(SCHEDULED_COMMAND)],
            "StartCalendarInterval": {"Hour": hour, "Minute": minute},
        }, handle)
    domain = f"gui/{os.getuid()}"
    subprocess.run(["/bin/launchctl", "bootstrap", domain, str(AGENT_PLIST)], check=True)
    print(f"Täglicher Abgleich um {hour:02d}:{minute:02d} Uhr eingerichtet.")
    print("Einmal sofort ausprobieren (empfohlen, damit macOS jetzt nach Berechtigungen fragt):")
    print("  ./setup.sh --zeitplan-testen")


def test_schedule() -> None:
    """Start the scheduled job right now, exactly as launchd would at the set time."""
    if not AGENT_PLIST.exists():
        sys.exit("Es ist kein täglicher Abgleich eingerichtet. Erst: ./setup.sh --taeglich-um HH:MM")
    subprocess.run(["/bin/launchctl", "kickstart", f"gui/{os.getuid()}/{settings.LAUNCH_AGENT_LABEL}"], check=True)
    print("Der geplante Abgleich wurde gestartet: Es öffnet sich gleich ein Terminal-Fenster.")
    print("Fragt macOS, ob Terminal auf „Dokumente“ (oder den Schlüsselbund) zugreifen darf: Erlauben.")
    print(f"Ergebnis danach im Protokoll: {settings.LOG_FILE}")


def remove_schedule(quiet: bool = False) -> None:
    domain = f"gui/{os.getuid()}"
    subprocess.run(["/bin/launchctl", "bootout", f"{domain}/{settings.LAUNCH_AGENT_LABEL}"],
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=False)
    if AGENT_PLIST.exists():
        AGENT_PLIST.unlink()
        if not quiet:
            print("Täglicher Abgleich entfernt.")
    elif not quiet:
        print("Es war kein täglicher Abgleich eingerichtet.")


def setup_schedule() -> None:
    print("\n— Automatischer Abgleich —")
    print("Der Mac kann einmal täglich ein Terminal-Fenster öffnen und neue Materialien laden.")
    print("Ist der Mac zu der Uhrzeit aus, läuft der Abgleich nach dem nächsten Aufwachen.")
    if not yes("Täglichen Abgleich einrichten?", default=True):
        remove_schedule(quiet=True)
        return
    while True:
        value = ask("Uhrzeit (HH:MM)", "09:00")
        try:
            hour, minute = (int(x) for x in value.split(":", 1))
            if 0 <= hour < 24 and 0 <= minute < 60:
                break
        except ValueError:
            pass
        print("Bitte im Format HH:MM eingeben, z. B. 08:30.")
    write_schedule(hour, minute)


def status() -> None:
    """Print the current configuration as JSON (for humans and AI assistants)."""
    import json

    data = settings.load()
    courses = settings.load_courses()
    schedule = None
    if AGENT_PLIST.exists():
        try:
            interval = plistlib.loads(AGENT_PLIST.read_bytes())["StartCalendarInterval"]
            schedule = f"{interval['Hour']:02d}:{interval['Minute']:02d}"
        except (OSError, KeyError, ValueError):
            schedule = "unbekannt"
    print(json.dumps({
        "installiert": True,
        "einstellungen_gespeichert": settings.SETTINGS_FILE.exists(),
        "zugangsdaten_gespeichert_fuer": settings.stored_username(),
        "materialordner": data["semester_dir"],
        "markdown_ordner": data["markdown_dir"],
        "taeglich_ohne_browserfenster": data["headless"],
        "markdown_nach_jedem_abgleich": data["markdown_after_sync"],
        "taeglicher_abgleich_um": schedule,
        "kurse_ausgewaehlt": list(courses) if courses else None,
        "ilias_sitzung_vorhanden": settings.SESSION_FILE.exists(),
    }, ensure_ascii=False, indent=2))


def parse_bool(value: str) -> bool:
    if value.casefold() in ("ja", "j", "yes", "y", "true", "1", "an"):
        return True
    if value.casefold() in ("nein", "n", "no", "false", "0", "aus"):
        return False
    raise argparse.ArgumentTypeError("bitte ja oder nein")


def parse_time(value: str) -> tuple[int, int]:
    try:
        hour, minute = (int(x) for x in value.split(":", 1))
    except ValueError:
        raise argparse.ArgumentTypeError("Format HH:MM, z. B. 09:00") from None
    if not (0 <= hour < 24 and 0 <= minute < 60):
        raise argparse.ArgumentTypeError("Format HH:MM, z. B. 09:00")
    return hour, minute


def apply_options(args: argparse.Namespace) -> None:
    """Non-interactive setup: only the options that were given are changed."""
    data = settings.load()
    if args.materialordner:
        data["semester_dir"] = str(Path(args.materialordner).expanduser().resolve())
    if args.markdown_ordner:
        data["markdown_dir"] = str(Path(args.markdown_ordner).expanduser().resolve())
    semester, markdown = Path(data["semester_dir"]).resolve(), Path(data["markdown_dir"]).resolve()
    if markdown == semester or semester in markdown.parents:
        sys.exit("FEHLER: Der Markdown-Ordner darf nicht im Materialordner liegen.")
    if args.hintergrund is not None:
        data["headless"] = args.hintergrund
    if args.markdown_nach_abgleich is not None:
        data["markdown_after_sync"] = args.markdown_nach_abgleich
    settings.save(data)
    semester.mkdir(parents=True, exist_ok=True)
    if data["markdown_after_sync"]:
        markdown.mkdir(parents=True, exist_ok=True)
    print(f"Einstellungen gespeichert in {settings.SETTINGS_FILE}")
    print(f"  Materialordner: {semester}")
    print(f"  Markdown:       {markdown if data['markdown_after_sync'] else 'aus'}")
    if args.taeglich_um:
        write_schedule(*args.taeglich_um)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Einrichtung des ILIAS-Downloaders. Ohne Optionen startet die Einrichtung mit Rückfragen.")
    group = parser.add_mutually_exclusive_group()
    group.add_argument("--status", action="store_true", help="Aktuelle Einrichtung als JSON anzeigen")
    group.add_argument("--zugangsdaten", action="store_true", help="Uni-ID/Passwort eingeben (fragt im Terminal)")
    group.add_argument("--zugangsdaten-loeschen", action="store_true", help="Uni-ID/Passwort aus dem Schlüsselbund entfernen")
    group.add_argument("--ordner", action="store_true", help="Ordner und Optionen mit Rückfragen ändern")
    group.add_argument("--zeitplan", action="store_true", help="Täglichen Abgleich mit Rückfragen ändern")
    group.add_argument("--zeitplan-entfernen", action="store_true", help="Täglichen Abgleich ausschalten")
    group.add_argument("--zeitplan-testen", action="store_true", help="Geplanten Abgleich jetzt sofort einmal starten")
    direct = parser.add_argument_group("ohne Rückfragen (z. B. für KI-Assistenten)")
    direct.add_argument("--materialordner", metavar="PFAD", help="Zielordner für Kursmaterialien")
    direct.add_argument("--markdown-ordner", metavar="PFAD", help="Zielordner für Markdown-Kopien")
    direct.add_argument("--hintergrund", type=parse_bool, metavar="ja|nein",
                        help="Täglichen Abgleich ohne Browserfenster ausführen")
    direct.add_argument("--markdown-nach-abgleich", type=parse_bool, metavar="ja|nein",
                        help="Nach jedem Abgleich Markdown-Kopien erzeugen")
    direct.add_argument("--taeglich-um", type=parse_time, metavar="HH:MM", help="Täglichen Abgleich einrichten")
    args = parser.parse_args()
    direct_given = any(getattr(args, name) is not None for name in
                       ("materialordner", "markdown_ordner", "hintergrund", "markdown_nach_abgleich", "taeglich_um"))
    try:
        if args.status:
            status()
        elif direct_given:
            apply_options(args)
        elif args.zugangsdaten:
            setup_credentials()
        elif args.zugangsdaten_loeschen:
            settings.delete_credentials()
            print("Zugangsdaten aus dem Schlüsselbund entfernt.")
        elif args.ordner:
            setup_folders()
        elif args.zeitplan:
            setup_schedule()
        elif args.zeitplan_testen:
            test_schedule()
        elif args.zeitplan_entfernen:
            remove_schedule()
        elif not sys.stdin.isatty():
            sys.exit("Keine Optionen angegeben und kein Terminal für Rückfragen. Siehe ./setup.sh --help")
        else:
            print("Einrichtung des ILIAS-Downloaders (Abbrechen jederzeit mit Ctrl+C)")
            setup_credentials()
            setup_folders()
            setup_schedule()
            print("\nFertig. Starte jetzt den ersten Abgleich mit:  ./run.sh")
            print("Beim ersten Lauf wählst du aus, welche Kurse heruntergeladen werden.")
    except (KeyboardInterrupt, EOFError):
        print("\nAbgebrochen.")
        sys.exit(1)


if __name__ == "__main__":
    main()
